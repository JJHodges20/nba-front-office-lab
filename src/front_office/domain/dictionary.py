"""Render the data dictionary from the table registry.

``docs/DATA_DICTIONARY.md`` is generated, never hand-edited: it is the registry in
readable form, and a test fails if the two drift apart.
"""

from __future__ import annotations

from collections.abc import Sequence

from front_office.domain.schema import Field, Provenance, TableContract
from front_office.domain.tables import PlannedTable

_PROVENANCE_MEANING = {
    Provenance.IDENTIFIER: "Keys, names and labels.",
    Provenance.MEASURED: "Recorded by the source: box-score counts, official cap figures, signed salaries.",
    Provenance.DERIVED: "Deterministic arithmetic on measured values.",
    Provenance.MODELED: "Output of a statistical model or weighted composite: an estimate, not a fact.",
    Provenance.ASSUMPTION: "Entered or chosen by the user.",
    Provenance.OPERATIONAL: "Pipeline bookkeeping: fetch times, run status, versions.",
}


def render_data_dictionary(
    tables: Sequence[TableContract], planned: Sequence[PlannedTable] = ()
) -> str:
    """The data dictionary as Markdown."""
    lines = [
        "# Data Dictionary",
        "",
        "<!-- Generated by `fol dictionary --write` from src/front_office/domain/tables. Do not edit by hand. -->",
        "",
        "Every table the lab stores, as declared by its data contract. A frame must satisfy",
        "its contract before it is stored, so this document describes what is actually in",
        "the database rather than what was once intended.",
        "",
        "## Conventions",
        "",
        "- Seasons are labelled by both years: `2025-26`.",
        "- Money is whole US dollars.",
        "- Shares and percentages are fractions between 0 and 1 unless a unit says otherwise.",
        "- Dates and times are UTC.",
        "- Missing text is null, never an empty string.",
        "",
        "## Provenance",
        "",
        "Each column declares where its values come from. The workbench uses this to keep",
        "measured statistics, modeled estimates and user assumptions visibly apart.",
        "",
        "| Provenance | Meaning |",
        "| --- | --- |",
    ]
    lines += [f"| `{kind.value}` | {meaning} |" for kind, meaning in _PROVENANCE_MEANING.items()]

    lines += [
        "",
        "## Tables",
        "",
        "| Table | Domain | Grain | Since |",
        "| --- | --- | --- | --- |",
    ]
    lines += [
        f"| [`{t.name}`](#{t.name}) | {t.domain} | {t.grain} | {t.introduced_in} |" for t in tables
    ]

    for contract in tables:
        lines += ["", *_table_section(contract)]

    if planned:
        lines += [
            "",
            "## Planned tables",
            "",
            "Called for by the roadmap; each gets a contract in the milestone that builds it.",
            "",
            "| Table | Domain | Purpose | Milestone |",
            "| --- | --- | --- | --- |",
        ]
        lines += [f"| `{p.name}` | {p.domain} | {p.purpose} | {p.milestone} |" for p in planned]

    return "\n".join(lines) + "\n"


def _table_section(contract: TableContract) -> list[str]:
    lines = [
        f"### {contract.name}",
        "",
        contract.description,
        "",
        f"- **Grain:** {contract.grain}",
        f"- **Primary key:** {', '.join(f'`{column}`' for column in contract.primary_key)}",
    ]
    if contract.indexes:
        indexes = "; ".join(", ".join(f"`{c}`" for c in index) for index in contract.indexes)
        lines.append(f"- **Indexes:** {indexes}")
    lines += [
        "",
        "| Column | Type | Required | Provenance | Unit | Description |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    lines += [_field_row(field) for field in contract.fields]
    return lines


def _field_row(field: Field) -> str:
    description = field.description
    if field.allowed is not None:
        description += " One of: " + ", ".join(f"`{value}`" for value in field.allowed) + "."
    if field.references is not None:
        description += f" References `{field.references}`."
    required = "no" if field.nullable else "yes"
    return (
        f"| `{field.name}` | {field.dtype.value} | {required} | {field.provenance.value} "
        f"| {field.unit or ''} | {description} |"
    )
