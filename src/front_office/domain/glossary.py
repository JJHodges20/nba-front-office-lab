"""Render the metric glossary from metric catalogs.

``docs/METRICS.md`` is generated, never hand-edited: it is the catalogs in readable
form, and a test fails if the two drift apart.
"""

from __future__ import annotations

from collections.abc import Mapping

from front_office.domain.metrics import MetricCatalog, MetricFormat, MetricSpec
from front_office.domain.schema import Provenance

_ORIGIN = {
    Provenance.MEASURED: "Published by the league - counted from the box score or from "
    "play-by-play - and passed through unchanged.",
    Provenance.DERIVED: "Computed by the lab from measured totals, with the formulas in "
    "`src/front_office/analytics/formulas.py`.",
    Provenance.MODELED: "Output of a fitted model: an estimate, not a fact. What the models "
    "are and how each was tested is in `docs/research/PLAYER_VALUE.md`, "
    "`docs/research/ROSTER_FIT.md` and `docs/research/POSTSEASON.md`.",
    Provenance.ASSUMPTION: "Entered or chosen by the user.",
}
_SHOWN_AS = {
    MetricFormat.COUNT: "whole number",
    MetricFormat.DECIMAL: "number",
    MetricFormat.PERCENT: "percentage",
    MetricFormat.SIGNED: "signed number",
    MetricFormat.MONEY: "US dollars",
}
_BETTER = {True: "higher", False: "lower", None: "neither"}


def render_metric_glossary(sections: Mapping[str, MetricCatalog]) -> str:
    """The metric glossary as Markdown: one section per catalog, one table per category."""
    lines = [
        "# Metric Glossary",
        "",
        "<!-- Generated by `fol metrics --write` from the metric catalogs in "
        "src/front_office. Do not edit by hand. -->",
        "",
        "Every metric the lab shows, as declared by its catalog entry. A screen takes a",
        "metric's label, description and format from the same entry, so this document",
        "describes what is on screen rather than what was once intended.",
        "",
        "## Reading the tables",
        "",
        "- **Origin** says where a number comes from:",
    ]
    used = {spec.provenance for catalog in sections.values() for spec in catalog}
    lines += [f"  - `{kind.value}`: {meaning}" for kind, meaning in _ORIGIN.items() if kind in used]
    lines += [
        "- **Better** says which direction is good. Percentiles and ranks are oriented by it, so a",
        "  high percentile always means good; where neither direction is better, it means high.",
        "- A rate whose denominator is zero is missing, not zero.",
    ]
    for title, catalog in sections.items():
        lines += ["", f"## {title}"]
        for category in catalog.categories:
            lines += [
                "",
                f"### {category}",
                "",
                "| Metric | Name | Key | Origin | Shown as | Better | Definition |",
                "| --- | --- | --- | --- | --- | --- | --- |",
            ]
            lines += [_metric_row(spec) for spec in catalog.in_category(category)]
    return "\n".join(lines) + "\n"


def _metric_row(spec: MetricSpec) -> str:
    return (
        f"| {spec.label} | {spec.name} | `{spec.key}` | {spec.provenance.value} "
        f"| {_SHOWN_AS[spec.format]} | {_BETTER[spec.higher_is_better]} | {spec.description} |"
    )
