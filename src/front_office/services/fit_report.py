"""Roster fit written up as a document: ``docs/research/ROSTER_FIT.md``.

Every figure comes from the evidence on file or from the database the report is run
against. It only words what :class:`~front_office.services.fit.FitService` returns.
"""

from __future__ import annotations

from front_office.domain.fit import MEASURES, Area, measures_in
from front_office.domain.fit_model import FitEvidence, Interval
from front_office.modeling.fit import LAG, TESTED
from front_office.services.fit import BOTTOM_THIRD, TOP_THIRD, FitStatus
from front_office.services.lab import Lab

DECISION = "docs/decisions/0012-roster-fit.md"
MOST = 2 / 3
"""The share of champions in the top third from which a measure is named as one they
tended to be strong on."""


class NoFitEvidence(RuntimeError):
    """There is no evidence on file, or no team profiles were built."""

    def __init__(self) -> None:
        super().__init__(
            "no roster fit to report: build the database and gather the evidence "
            "(fol build, then fol fit test --write)"
        )


def fit_report(lab: Lab) -> str:
    """The research document for the evidence on file and the lab's current database."""
    service = lab.fit
    status, evidence = service.status(), service.evidence()
    if evidence is None or not status.seasons:
        raise NoFitEvidence
    built = lab.status()
    parts = [
        "# Do These Players Make Sense Together?",
        "",
        "Roster fit: what a roster is described by, and whether any of it says something "
        "the sum of its players' impacts does not. Generated by `fol fit report --write` "
        f"from revision {evidence.revision} of the fit evidence (gathered "
        f"{evidence.fitted_at:%Y-%m-%d}) and build {built.build_id}; do not edit it by hand "
        "- gather the evidence again, rebuild, and run the command again.",
        "",
        "> A roster's profile is description: averages of what its players did, for the "
        "minutes they played, and counts of the roles they fill by rules written down in "
        "`configs/archetypes.yaml`. Whether a profile predicts anything beyond the players' "
        "impacts added up is the question tested here, on seasons the test had not seen.",
        "",
        *_notices(status),
        *_what(),
        *_how(evidence),
        *_alone(evidence),
        *_together(evidence),
        *_champions(lab),
        *_limits(),
    ]
    return "\n".join(parts).rstrip("\n") + "\n"


def _notices(status: FitStatus) -> list[str]:
    if status.is_current:
        return []
    return [
        f"> **Out of date.** The evidence was gathered against value model "
        f"{status.value_model_version} and roles {status.archetype_version}; the database "
        f"was built with {status.applied_value_version} and "
        f"{status.applied_archetype_version}. Run: fol fit test --write",
        "",
    ]


def _what() -> list[str]:
    lines = [
        "## What a roster is described by",
        "",
        "The roadmap asks six questions of a roster - offense, defense, the possession "
        "battle, structure, depth and usage - and this is what thirty seasons of box scores, "
        "listed positions, the value model and the role rules can say about each. Every "
        "average weighs a player by the minutes played for the roster; roles are counted in "
        "the rotation, the ten players with the most minutes, and on the bench, the sixth to "
        "tenth. A real team is placed among the teams of its own season, so eras compare.",
        "",
    ]
    for area in Area:
        items = measures_in(area)
        lines += [f"**{area}**", ""]
        lines += [f"- *{item.name}*: {item.description}" for item in items]
        lines.append("")
    return lines


def _how(evidence: FitEvidence) -> list[str]:
    tested = len(evidence.tested)
    return [
        "## How it was tested",
        "",
        "The value model's own test predicted every team-season from 2006-07 on from its "
        "players, each taken alone, and recorded what each prediction missed. Fit would show "
        "in those misses, if it shows anywhere. Each fit measure was computed from the "
        f"players' profiles of the season before ({LAG} season back), weighted by the minutes "
        "they then played for the team, so that nothing of the season predicted leaks in; "
        "then it was asked, one season at a time with only earlier seasons to learn from, "
        "whether it explained the misses. The sums of parts themselves are what fit is "
        f"measured beyond, so {tested} of the {len(MEASURES)} measures were tested.",
        "",
        f"- {evidence.team_seasons} team-seasons, {evidence.first_test_season} to "
        f"{evidence.last_test_season}, against value model {evidence.value_model_version} "
        f"and roles {evidence.archetype_version}.",
        f"- The value model's predictions missed by {evidence.baseline_rmse:.2f} points of net "
        "rating (RMSE) on those team-seasons.",
        "- Each correction is least squares with an intercept on standardised measures. "
        f"Intervals are {evidence.spec.confidence:.0%}, from resampling whole seasons "
        f"{evidence.spec.resamples:,} times: the teams of one season play each other and are "
        "not independent.",
        "",
    ]


def _alone(evidence: FitEvidence) -> list[str]:
    lines = [
        "## Each measure alone",
        "",
        "The sum of the parts corrected by one measure at a time. A coefficient is points of "
        "net rating per standard deviation of the measure, fitted on every season; the change "
        "is the out-of-sample error less the sum of the parts' own, so negative helps.",
        "",
        "| Measure | Area | Per standard deviation (interval) | RMSE | Change (interval) | Verdict |",
        "| --- | --- | --- | ---: | --- | --- |",
    ]
    for item in evidence.measures:
        verdict = "clear of zero" if item.is_distinguishable else "cannot be told from nothing"
        lines.append(
            f"| {item.name} | {item.area} | {item.coefficient:+.2f} ({item.coefficient_low:+.2f} "
            f"to {item.coefficient_high:+.2f}) | {item.rmse:.2f} | {_span(item.change)} | {verdict} |"
        )
    clear = evidence.distinguishable
    lines.append("")
    if clear:
        names = ", ".join(item.name.lower() for item in clear)
        lines.append(
            f"Clear of zero on its own: {names}. Everything else cannot be told from adding "
            "nothing on this evidence."
        )
    else:
        lines.append(
            "No measure, on its own, leaves the sum of the parts missing by clearly less. "
            "Several coefficients are clear of zero when fitted on every season at once, "
            "but what they explain in one season does not carry to the next."
        )
    return [*lines, ""]


def _together(evidence: FitEvidence) -> list[str]:
    combined = evidence.combined
    lines = [
        "## Every measure together",
        "",
        "| Correction | RMSE | Change (interval) |",
        "| --- | ---: | --- |",
        f"| Sum of the parts alone | {evidence.baseline_rmse:.2f} | |",
        f"| With every measure | {combined.rmse:.2f} | {_span(combined.change)} |",
        "",
    ]
    if combined.is_usable:
        lines.append(
            "**The correction is applied to rosters.** Together the measures leave the sum of "
            "the parts missing by clearly less, and a roster's profile adds the correction to "
            "its sum of parts on the Roster Fit page."
        )
    else:
        lines.append(
            "**No correction is applied to rosters.** Together the measures do not leave the "
            "sum of the parts missing by clearly less"
            + (
                " - they leave it missing by more, which is what fitting many weights to few "
                "seasons does when there is nothing to find."
                if combined.change.low > 0
                else "."
            )
            + " The Roster Fit page shows a roster's profile as description and its sum of "
            "parts as the estimate."
        )
    lines += [
        "",
        "**With one area left out**",
        "",
        "| Left out | RMSE | RMSE less the full correction's (interval) | Verdict |",
        "| --- | ---: | --- | --- |",
    ]
    for item in combined.ablations:
        verdict = (
            "missed"
            if item.change.low > 0
            else "better without"
            if item.change.high < 0
            else "cannot be told"
        )
        lines.append(f"| {item.label} | {item.rmse:.2f} | {_span(item.change)} | {verdict} |")
    return [*lines, ""]


def _champions(lab: Lab) -> list[str]:
    champions = lab.fit.champions()
    if champions.empty or champions["champions"].max() == 0:
        return []
    total = int(champions["champions"].max())
    lines = [
        "## Where the champions' rosters stood",
        "",
        f"Each of the {total} champions on record, placed among the teams of its own season "
        "on each measure by what its players showed that season. History, not a recipe: the "
        "test above is what says whether a measure matters beyond the parts, and a champion "
        "is first of all a team whose parts add up.",
        "",
        "| Measure | Area | Median percentile | In the top third | In the bottom third |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    for row in champions.itertuples():
        lines.append(
            f"| {row.name} | {row.area} | {row.median_percentile:.0f} | {row.top_third} | "
            f"{row.bottom_third} |"
        )
    strong = champions[champions["top_third"] >= MOST * total]
    weak = champions[champions["bottom_third"] >= MOST * total]
    lines.append("")
    if not strong.empty:
        lines.append(
            f"At least two champions in three were in the top third of their season "
            f"({TOP_THIRD:.0f}th percentile and up) on: "
            + "; ".join(name.lower() for name in strong["name"])
            + "."
        )
    if not weak.empty:
        lines.append(
            f"At least two in three were in the bottom third ({BOTTOM_THIRD:.0f}th percentile "
            "and down) on: " + "; ".join(name.lower() for name in weak["name"]) + "."
        )
    if strong.empty and weak.empty:
        lines.append("On no measure were two champions in three at one end of the league.")
    return [*lines, ""]


def _limits() -> list[str]:
    return [
        "## What it cannot tell you",
        "",
        "- **The measures are proxies.** A box score records no screens, no switches, no "
        "closeouts and nobody's athleticism; the roles are rules on what it does record.",
        "- **Nothing here says how players would play together.** A profile is an average "
        "over what each player did on the team they were on. The test asks whether such "
        "averages predicted anything beyond the parts; that is as far as it goes.",
        f"- **The test is bounded by the sample.** The {len(TESTED)} measures were tested on "
        "the seasons the value model's test covers, with the previous season's profiles. An "
        "effect too small to show there is not ruled out; it is only not found.",
        "- **Roles follow the rules and the value model.** Change either and the counts move; "
        "every profile says which versions it rests on.",
        "",
        f"The decision record: `{DECISION}`.",
    ]


def _span(interval: Interval) -> str:
    return f"{interval.difference:+.2f} ({interval.low:+.2f} to {interval.high:+.2f})"
