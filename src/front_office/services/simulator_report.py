"""The simulator written up as a document: ``docs/research/SIMULATOR.md``.

Every figure comes from the parameters on file or from the database the report is run
against; it only words what :class:`~front_office.services.simulator.SimulatorService`
returns.
"""

from __future__ import annotations

from front_office.domain.simulator import SimulatorModel
from front_office.domain.stages import BRACKET_STAGE_KEYS, stage
from front_office.modeling.postseason import probability_key
from front_office.services.lab import Lab
from front_office.services.simulator import FIT_COMMAND, SimulatorStatus

DECISION = "docs/decisions/0015-simulator.md"


class NoSimulatorModel(RuntimeError):
    """There are no parameters on file, or no season to look ahead to."""

    def __init__(self) -> None:
        super().__init__(
            "no simulator to report: build the database, fit the value and postseason models, "
            f"then measure the simulator's parameters ({FIT_COMMAND})"
        )


def simulator_report(lab: Lab) -> str:
    """The research document for the parameters on file and the lab's current database."""
    service = lab.simulator
    status, model = service.status(), service.model()
    if model is None or not status.is_available:
        raise NoSimulatorModel
    built = lab.status()
    parts = [
        "# What a Season Could Bring",
        "",
        "The scenario simulator: seasons drawn for a roster from parts the lab has tested, "
        "the few parameters measured for it, the test of the wins it gives, and the season "
        "ahead as it draws it for every team. Generated by `fol simulate report --write` from "
        f"revision {model.revision} of the simulator's parameters (measured "
        f"{model.fitted_at:%Y-%m-%d}) and build {built.build_id}; do not edit it by hand - "
        "measure again, rebuild, and run the command again.",
        "",
        "> Every figure here is an estimate with an interval. A scenario's assumptions - who "
        "is on the roster, who misses games, who improves - are the user's; what they come to "
        "is the model's, and nothing is a guarantee.",
        "",
        *_notices(status),
        *_what(model),
        *_measured(model),
        *_test(model),
        *_season_ahead(lab),
        *_limits(),
    ]
    return "\n".join(parts).rstrip("\n") + "\n"


def _notices(status: SimulatorStatus) -> list[str]:
    if status.is_current:
        return []
    return [
        f"> **Out of date.** The parameters were measured against value model "
        f"{status.value_model_version}; the database was built with "
        f"{status.applied_value_version}. Run: `{FIT_COMMAND}`, then this command again.",
        "",
    ]


def _what(model: SimulatorModel) -> list[str]:
    return [
        "## What a season is drawn from",
        "",
        "A scenario is a roster for the season ahead - a real team as it stands, or a roster "
        "built in the Team Builder - with the user's changes: players added and removed, "
        "the games each is expected to miss, how far each comes out from the value model's "
        "projection, the share of the minutes each plays. Each simulated season then:",
        "",
        "- draws every player's impact around the value model's projection, as far off as "
        "projections of players that well known have come out;",
        "- draws the games every player misses from what rotation players have missed, "
        "around what the scenario assumes;",
        "- adds the parts up for the minutes drawn - five slots of replacement level plus "
        "what each player adds above it - exactly as the optimizer and the Roster Fit page "
        "do, and draws the miss on a team's strength that the value model's test leaves "
        "once the players' own spread is taken out;",
        "- adds a season's own noise to get the rating the season shows, and turns that "
        "into wins with the wins a point of net rating has been worth, plus the residual "
        "wins carry;",
        "- reads the postseason model's season steps for the chance of each stage, with the "
        "interval its resampled steps give.",
        "",
        f"The value model (`{model.value_model_version}`) and the postseason model "
        f"(`{model.postseason_model_version or 'none on file when measured'}`) were each "
        "tested on seasons they had not seen; their research documents say how. The "
        f"parameters measured here are in `{DECISION}`.",
        "",
    ]


def _measured(model: SimulatorModel) -> list[str]:
    on = model.fitted_on
    lines = [
        "## What was measured",
        "",
        f"On {on.team_seasons:,} team-seasons, {on.games:,} regular-season games and "
        f"{on.player_seasons:,} player-seasons, {on.first_season} to {on.last_season}.",
        "",
        "| Parameter | Value | What it is |",
        "| --- | --- | --- |",
        f"| The value model's miss | {model.value_error:.2f} | How far its prediction of a "
        "team's net rating fell from what the season showed, out of sample (RMSE). |",
        f"| A season's own noise | {model.season_noise:.2f} | How far a season's net rating "
        "strays from the team's strength, from the spread of its game margins, over the last "
        f"{model.spec.noise_seasons} seasons. |",
        f"| Miss on a team's strength | {model.strength_error:.2f} | What is left of the "
        "value model's miss once a season's noise is taken out. |",
        f"| Wins per point of net rating | {model.wins_per_point:.2f} | Fitted for "
        f"{model.wins_season}, the latest season with games. |",
        f"| Residual wins | {model.wins_residual:.2f} | How far wins per 82 stray from what a "
        "season's net rating gives, over the same seasons. |",
        "",
        "A season's noise by era:",
        "",
        "| Era | Seasons | Team-seasons | Noise |",
        "| --- | --- | --- | --- |",
        *(
            f"| {item.label} | {item.first_season} to {item.last_season} | {item.team_seasons} | "
            f"{item.noise:.2f} |"
            for item in model.noise_by_era
        ),
        "",
        "How far projections have missed, by how well the value model knew the player "
        "(weighted by the minutes the player went on to play):",
        "",
        "| Projection reliability | Player-seasons | Typical direction | Typical size |",
        "| --- | --- | --- | --- |",
        *(
            f"| {item.lower:.2f} to {item.upper:.2f} | {item.players:,} | {item.mean_miss:+.2f} | "
            f"{item.spread:.2f} |"
            for item in model.development
        ),
        "",
        f"The share of the season missed by rotation players (at least "
        f"{model.spec.rotation_minutes:,} minutes), {model.missed.players:,} player-seasons, "
        f"mean {model.missed.mean:.1%}:",
        "",
        "| Quantile | Share of the season missed |",
        "| --- | --- |",
        *(f"| {item.level:.0%} | {item.value:.1%} |" for item in model.missed.quantiles),
        "",
    ]
    return lines


def _test(model: SimulatorModel) -> list[str]:
    test = model.test
    return [
        "## The wins test",
        "",
        f"For each of the {test.team_seasons} team-seasons the value model predicted out of "
        f"sample ({test.first_test_season} to {test.last_test_season}), "
        f"{model.spec.test_simulations:,} seasons were drawn from the predicted rating with "
        "the value model's miss and the residual wins carry, and the wins that happened were "
        "set against what the seasons gave.",
        "",
        "| Interval | Held the wins that happened | Cases |",
        "| --- | --- | --- |",
        *(f"| {item.level:.0%} | {item.share:.1%} | {item.cases} |" for item in test.coverage),
        "",
        f"The median of the seasons drawn missed the wins that happened by {test.mae:.1f} "
        f"wins on average ({test.rmse:.1f} RMSE), against {test.baseline_rmse:.1f} for giving "
        "every team an even record. An interval that holds the wins that happened about as "
        "often as it claims is one a reader can lean on; one that holds them more often is "
        "too wide, less often too narrow.",
        "",
    ]


def _season_ahead(lab: Lab) -> list[str]:
    league = lab.simulator.league()
    if league.empty:
        return []
    status = lab.simulator.status()
    keys = [probability_key(key) for key in BRACKET_STAGE_KEYS]
    return [
        f"## The season ahead, as drawn: {status.upcoming}",
        "",
        "Every team with projected players, as it stands and with nothing assumed: the "
        "players whose current team it is, each with the value model's projection, missing "
        "games as rotation players have. A team's rating is the sum of its parts; players "
        "without a projection count as replacement players. The field is not in it: each "
        "team is drawn as a team of its strength entering any season, so the chances need "
        "not add up across the league.",
        "",
        "| Team | Players | Projected | Rating | Wins | "
        + " | ".join(stage(key).short for key in BRACKET_STAGE_KEYS)
        + " |",
        "| --- | --- | --- | --- | --- | " + " | ".join("---" for _ in keys) + " |",
        *(
            f"| {row['team_name']} | {row['players']} | {row['projected']} | {row['rating']:+.1f} | "
            f"{row['wins']:.0f} ({row['wins_low']:.0f} to {row['wins_high']:.0f}) | "
            + " | ".join(f"{row[key]:.0%}" for key in keys)
            + " |"
            for _, row in league.iterrows()
        ),
        "",
    ]


def _limits() -> list[str]:
    return [
        "## What this does not say",
        "",
        "- The field is not in it. Each team is drawn alone, as a team of its strength "
        "entering any season; the chances of the thirty teams need not add up, and a trade "
        "that strengthens one team does not weaken the other on this page.",
        "- A roster is the parts added up. The value model found no fit measure that "
        "predicts beyond that, so none is used; how the players would play together is not "
        "modelled.",
        "- Who misses games is drawn from what rotation players have missed, not from "
        "anyone's medical history, and development from how far projections have missed, "
        "not from any one player's trajectory. Both presets are assumptions, and a figure "
        "set for a player is the user's.",
        "- The season ahead's projections rest on the value model's own limits: defense is "
        "the weak side, and projected minutes know nothing of depth charts or contracts.",
        "- A chance is an estimate with an interval; the wins test is the evidence for "
        "reading it as one.",
        "",
    ]


__all__ = ["NoSimulatorModel", "simulator_report"]
