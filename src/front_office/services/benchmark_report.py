def _tied_standings(lab: Lab, view: EraView) -> int:
    """Conference standings in the era where two teams share a place."""
    seasons = lab.read("team_seasons", {"season": list(view.seasons)})
    placed = seasons.dropna(subset=["conference", "conference_rank"])
    shared = placed.duplicated(["season", "conference", "conference_rank"], keep=False)
    return int(placed[shared].drop_duplicates(["season", "conference"]).shape[0])


def _group_label(group: str) -> str:
    return next(stage.label for stage in STAGES if stage.key == group)


def _past(stage: str) -> str:
    """A stage as the rest of a sentence: "teams that <made the playoffs>"."""
    label = _group_label(stage)
    return label[0].lower() + label[1:]


def _share(rate: float, *, digits: int = 0) -> str:
    if rate != rate:
        return "-"
    return f"{rate * 100:.{digits}f}%"


def _range(low: float, high: float) -> str:
    if low != low or high != high:
        return "-"
    return f"{low * 100:.0f}% to {high * 100:.0f}%"


def _count(row: pd.Series) -> str:
    return f"{int(row['inside'])} of {int(row['teams'])}"


def _value(catalog: MetricCatalog, key: str, value: float) -> str:
    return catalog[key].format_value(value)
