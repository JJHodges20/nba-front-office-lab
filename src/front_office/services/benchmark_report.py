"""The benchmark research written up as a document: ``docs/research/BENCHMARKS.md``.

Every sentence and table is produced from the database it is run against, so the
document cannot drift from the data: run it again after a refresh and it says what the
data now says. It only assembles and words what :class:`BenchmarkService` returns.
"""

from __future__ import annotations

import pandas as pd

from front_office.analytics.benchmarks import EVERY_TEAM, STAGE_KEYS, STAGES
from front_office.domain.metrics import MetricCatalog
from front_office.services.benchmarks import BenchmarkService, EraView, floor
from front_office.services.lab import Lab

# The stages a profile is written for: the later rounds, where the question is "what
# did the teams that got this far look like". The whole field is the reference.
PROFILED_STAGES = ("made_playoffs", "made_conference_finals", "made_finals", "won_championship")
# (teams that reached, the field they are set against): None is every other team.
COMPARISONS: tuple[tuple[str, str | None], ...] = (
    ("made_playoffs", None),
    ("won_a_round", "made_playoffs"),
    ("made_conference_finals", "won_a_round"),
    ("won_championship", None),
)
TIED_PLACES_NOTE = (
    "In {count} of this era's conference standings the league leaves teams with equal "
    "records on the same place, so there a place is not always the seed a team played "
    "from. The published place is used as it stands."
)


def benchmark_report(lab: Lab) -> str:
    """The research document for the lab's current database, as Markdown."""
    service = lab.benchmarks
    status = lab.status()
    views = [service.view(era) for era in service.eras]
    main = views[0]
    built = "" if status.built_at is None else f" of {status.built_at:%Y-%m-%d}"
    parts = [
        "# What Contenders Have Looked Like",
        "",
        "Benchmark research from the lab's own history of team seasons. Generated by "
        f"`fol benchmarks --write` from build {status.build_id}{built}; do not edit it by "
        "hand - change the data or the code and run the command again.",
        "",
        "> Everything here describes seasons that are over: how often past teams of a "
        "kind reached each stage of the postseason, and what the teams that got there "
        "looked like. It is not a forecast for any team. There is one champion a season, "
        "so every share comes with the count behind it and an interval that says how far "
        "a share drawn from so few cases can be trusted.",
        "",
        *_coverage(views),
        *_reading_guide(),
    ]
    if main.teams == 0:
        parts += ["No completed season is on record yet, so there is nothing to describe.", ""]
        return "\n".join(parts)
    parts += [
        *_rates_section(service, main, "wins_per_82", "By record"),
        *_rates_section(service, main, "net_rating", "By net rating"),
        *_seed_section(service, main, _tied_standings(lab, main)),
        *_profile_section(service, main),
        *_separation_section(service, main),
        *_era_section(service, views),
        *_limits(),
    ]
    return "\n".join(parts)


# --- sections ---------------------------------------------------------------------------


def _coverage(views: list[EraView]) -> list[str]:
    lines = [
        "## Seasons covered",
        "",
        "| Era | Seasons | Team-seasons | Postseason | Playoffs | Won a series "
        "| Conference finals | Finals | Champions |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for view in views:
        reached = " | ".join(str(view.reached[key]) for key in STAGE_KEYS)
        span = f"{view.span} ({len(view.seasons)})" if view.seasons else view.span
        lines.append(f"| {view.era.name} | {span} | {view.teams} | {reached} |")
    lines.append("")
    for view in views:
        if view.era.note:
            lines.append(f"- **{view.era.name}.** {view.era.note}")
    lines += [
        "",
        "Only seasons whose postseason is complete are counted. The eras are defined in "
        "`configs/eras.yaml` and can be changed there.",
        "",
    ]
    return lines


def _reading_guide() -> list[str]:
    stages = "; ".join(
        f"*{stage.label.lower()}* - {stage.description[:-1].lower()}" for stage in STAGES
    )
    return [
        "## How to read it",
        "",
        "- **Stage.** Each stage contains every later one: " + stages + ".",
        "- **Wins per 82.** Winning percentage times 82, so that seasons cut short by a "
        "lockout or a pandemic compare with the rest.",
        "- **Band.** Teams are grouped in bands of a measure. A band holds its lower edge "
        "and stops short of its upper one: *45 to 50* holds 45 and not 50. A band is a "
        "way of grouping, not a threshold.",
        "- **Interval.** The 95% Wilson interval for a share: the range the long-run rate "
        "plausibly lies in, given how few cases there are. *0 of 40* does not mean never.",
        "- **League rank.** A team's rank on a metric among the teams of its own season; "
        "1 is best. Ranks compare across eras where raw values do not.",
        "- **Concordance.** Take a team that reached a stage and a team of the same "
        "season that did not. Concordance is how often the first has the better value "
        "of a metric: 50% is a coin flip, 100% is always. Its interval comes from "
        "drawing whole seasons again, because the teams of one season are not "
        "independent of each other.",
        "",
    ]


def _rates_section(service: BenchmarkService, view: EraView, measure: str, title: str) -> list[str]:
    rates = service.rates(view.era, measure)
    spec = service.metrics[measure]
    lines = [
        f"## How far teams went: {title.lower()}",
        "",
        f"{view.era.name}, {view.span}. Share of the teams in each band of "
        f"{spec.name.lower()} that reached each stage; the last column gives the "
        "champions as a count with the interval for their share.",
        "",
        f"| {spec.name} | Teams | Postseason | Playoffs | Won a series | Conference finals "
        "| Finals | Champion |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for band, rows in rates.groupby("band", sort=False):
        by_stage = rows.set_index("stage")
        shares = " | ".join(_share(by_stage.at[key, "rate"]) for key in STAGE_KEYS[:-1])
        champion = by_stage.loc["won_championship"]
        lines.append(
            f"| {band} | {int(champion['teams'])} | {shares} | "
            f"{int(champion['reached'])} of {int(champion['teams'])} "
            f"({_range(champion['low'], champion['high'])}) |"
        )
    lines += ["", *_floor_remark(rates, spec.name.lower()), ""]
    return lines


def _floor_remark(rates: pd.DataFrame, measure: str) -> list[str]:
    """What the bands below the lowest champion add up to."""
    found = floor(rates, "won_championship")
    if found is None:
        return ["No team in this era won a championship."]
    if found.teams_below == 0:
        return [f"The lowest band of {measure} already holds a champion."]
    return [
        f"No champion came from below the *{found.band}* band. The {found.teams_below} "
        f"teams in the bands beneath it won no title, which by the interval is consistent "
        f"with a long-run rate of up to {_share(found.ceiling, digits=1)} - rare, on "
        "this evidence, rather than impossible."
    ]


def _seed_section(service: BenchmarkService, view: EraView, tied: int) -> list[str]:
    rates = service.rates(view.era, "conference_rank")
    lines = [
        "## How far teams went: by seed",
        "",
        f"{view.era.name}, {view.span}. Counts of teams from each place in the final "
        "conference standings.",
        "",
        "| Seed | Teams | Postseason | Playoffs | Won a series | Conference finals | Finals "
        "| Champion |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for band, rows in rates.groupby("band", sort=False):
        by_stage = rows.set_index("stage")
        counts = " | ".join(str(int(by_stage.at[key, "reached"])) for key in STAGE_KEYS)
        lines.append(f"| {band} | {int(by_stage['teams'].iloc[0])} | {counts} |")
    lines.append("")
    champions = rates[(rates["stage"] == "won_championship") & (rates["reached"] > 0)]
    if not champions.empty:
        worst = champions["band"].iloc[-1]
        total = int(champions["reached"].sum())
        lines += [f"All {total} champions were seeded {worst} or better in their conference.", ""]
    if tied:
        lines += [TIED_PLACES_NOTE.format(count=tied), ""]
    return lines


def _profile_section(service: BenchmarkService, view: EraView) -> list[str]:
    profiles = service.profiles(view.era)
    catalog = service.metrics
    values = profiles[profiles["kind"] == "value"]
    ranks = profiles[profiles["kind"] == "rank"]
    lines = [
        "## What the teams at each stage looked like",
        "",
        f"{view.era.name}, {view.span}.",
        "",
        "### In their own units",
        "",
        "Measures that mean the same in every era. The lowest and the highest are real "
        "teams; the other points are positions in the spread of the group.",
        "",
        "| Measure | Group | Teams | Lowest | 10% | Median | 90% | Highest |",
        "| --- | --- | ---: | --- | ---: | ---: | ---: | --- |",
    ]
    for metric, rows in values.groupby("metric", sort=False):
        spec = catalog[metric]
        for group in PROFILED_STAGES:
            row = rows[rows["group"] == group].iloc[0]
            if row["teams"] == 0:
                continue
            lines.append(
                f"| {spec.name} | {row['group_label']} | {int(row['teams'])} "
                f"| {spec.format_value(row['lowest'])} ({row['lowest_team']}) "
                f"| {spec.format_value(row['p10'])} | {spec.format_value(row['median'])} "
                f"| {spec.format_value(row['p90'])} "
                f"| {spec.format_value(row['highest'])} ({row['highest_team']}) |"
            )
    lines += [
        "",
        "### By league rank in their own season",
        "",
        "Median league rank of each group, with the ranks that the middle 80% of the "
        "group fell between. Rank 1 is the best figure in the league that season, "
        "whichever direction is better for the metric. Pace and three-point rate have "
        "no better direction; there rank 1 is simply the highest.",
        "",
        "| Metric | " + " | ".join(_group_label(group) for group in PROFILED_STAGES) + " |",
        "| --- | " + " | ".join("---" for _ in PROFILED_STAGES) + " |",
    ]
    for metric, rows in ranks.groupby("metric", sort=False):
        cells = []
        for group in PROFILED_STAGES:
            row = rows[rows["group"] == group].iloc[0]
            cells.append(
                "-"
                if row["teams"] == 0
                else f"{row['median']:g} ({row['p10']:.0f} to {row['p90']:.0f})"
            )
        lines.append(f"| {catalog[metric].name} | " + " | ".join(cells) + " |")

    counts = service.rank_counts(view.era)
    lines += [
        "",
        "### How many ranked near the top of the league",
        "",
        "Count of each group inside a league-rank cutoff that season. *Both ends* means "
        "inside the cutoff on offensive and on defensive rating at once.",
        "",
        "| Group | Teams | Net rating: 1st | Top 3 | Top 5 | Top 10 | Both ends: top 5 "
        "| Both ends: top 10 |",
        "| --- | ---: | --- | --- | --- | --- | --- | --- |",
    ]
    for group in (*PROFILED_STAGES, EVERY_TEAM):
        mine = counts[counts["group"] == group].set_index(["basis", "cutoff"])
        teams = int(mine["teams"].iloc[0])
        if teams == 0:
            continue
        cells = [_count(mine.loc[("Net rating", cutoff)]) for cutoff in (1, 3, 5, 10)]
        cells += [_count(mine.loc[("Both ends", cutoff)]) for cutoff in (5, 10)]
        lines.append(f"| {mine['group_label'].iloc[0]} | {teams} | " + " | ".join(cells) + " |")
    lines.append("")
    return lines


def _separation_section(service: BenchmarkService, view: EraView) -> list[str]:
    lines = [
        "## What separates them",
        "",
        f"{view.era.name}, {view.span}. One metric at a time: how often the team that "
        "reached a stage had the better value than a team of the same season that did "
        "not. Record and net rating sum up everything a team does and lead every table; "
        "the question is which ingredients come closest to them, and which do not "
        "separate teams at all. Rows run from the highest figure to the lowest. Near 50% "
        "a metric separates nothing; below it, the teams that reached the stage tended to "
        "have the worse value - or, for pace and three-point rate, the lower one.",
        "",
    ]
    for reached, among in COMPARISONS:
        table = service.separation(view.era, reached, among=among)
        if table["pairs"].max() == 0:
            continue
        field = (
            "every other team"
            if among is None
            else f"teams that {_past(among)} and went no further"
        )
        first = table.iloc[0]
        lines += [
            f"### Teams that {_past(reached)}, against {field}",
            "",
            f"{int(first['reached'])} teams against {int(first['others'])}, in "
            f"{int(first['seasons'])} seasons ({int(first['pairs']):,} same-season pairs).",
            "",
            "| Metric | Concordance | 95% interval | Median league rank: reached | Others |",
            "| --- | ---: | --- | ---: | ---: |",
        ]
        for row in table.itertuples():
            lines.append(
                f"| {row.name} | {_share(row.concordance)} | {_range(row.low, row.high)} "
                f"| {row.reached_median_rank:g} | {row.others_median_rank:g} |"
            )
        lines.append("")
    return lines


def _era_section(service: BenchmarkService, views: list[EraView]) -> list[str]:
    catalog = service.metrics
    lines = [
        "## The eras side by side",
        "",
        "The champions of each era. Small eras have few champions; read the last rows "
        "as anecdotes.",
        "",
        "| Era | Champions | Fewest wins per 82 | Median wins per 82 | Median net rating "
        "| Worst seed | Top 5 in net rating | Top 10 at both ends |",
        "| --- | ---: | --- | ---: | ---: | ---: | --- | --- |",
    ]
    for view in views:
        if view.reached["won_championship"] == 0:
            lines.append(f"| {view.era.name} | 0 | - | - | - | - | - | - |")
            continue
        profiles = service.profiles(view.era)
        champions = profiles[
            (profiles["group"] == "won_championship") & (profiles["kind"] == "value")
        ].set_index("metric")
        counts = service.rank_counts(view.era)
        mine = counts[counts["group"] == "won_championship"].set_index(["basis", "cutoff"])
        wins, net, seed = (
            champions.loc[key] for key in ("wins_per_82", "net_rating", "conference_rank")
        )
        lines.append(
            f"| {view.era.name} | {int(wins['teams'])} "
            f"| {_value(catalog, 'wins_per_82', wins['lowest'])} ({wins['lowest_team']}) "
            f"| {_value(catalog, 'wins_per_82', wins['median'])} "
            f"| {_value(catalog, 'net_rating', net['median'])} "
            f"| {seed['highest']:g} "
            f"| {_count(mine.loc[('Net rating', 5)])} "
            f"| {_count(mine.loc[('Both ends', 10)])} |"
        )
    lines.append("")
    return lines


def _limits() -> list[str]:
    return [
        "## What this cannot say",
        "",
        "- **It is description, not prediction.** A rate here is how often something "
        "happened to past teams in a band. It is not the chance that a particular team "
        "does it this season; that needs a model evaluated on seasons it has not seen.",
        "- **One metric at a time.** The separation tables do not say what a metric adds "
        "once the others are known, and they say nothing about cause.",
        "- **Regular-season figures only.** How a team played in the playoffs themselves "
        "is not used to describe it.",
        "- **Nothing on roster make-up or payroll.** The lab holds player detail for "
        "recent seasons only and no contract history, so how contenders were built and "
        "what they cost cannot be measured yet.",
        "- **Few champions.** One a season. Anything said about them rests on a few dozen "
        "teams at most, and on a handful in the short eras.",
        "",
    ]


