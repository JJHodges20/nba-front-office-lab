"""The postseason model written up as a document: ``docs/research/POSTSEASON.md``.

Every figure comes from the model on file or from the database the report is run
against. It only words what :class:`~front_office.services.postseason.PostseasonService`
returns.
"""

from __future__ import annotations

from front_office.domain.postseason import (
    Calibration,
    Comparison,
    PostseasonModel,
    ReliabilityBin,
    StageEvaluation,
)
from front_office.domain.stages import BRACKET_STAGE_KEYS, stage
from front_office.modeling.postseason import probability_key
from front_office.services.lab import Lab
from front_office.services.postseason import FIT_COMMAND, PostseasonStatus

DECISION = "docs/decisions/0014-postseason-model.md"
CURVE_POINTS = (-5.0, 0.0, 3.0, 5.0, 7.0, 9.0, 11.0)
"""Net ratings the season model is read at in the document."""


class NoPostseasonModel(RuntimeError):
    """There is no model on file, or no decided postseason in the database."""

    def __init__(self) -> None:
        super().__init__(
            "no postseason model to report: build the database and fit the model "
            f"(fol build, then {FIT_COMMAND})"
        )


def postseason_report(lab: Lab) -> str:
    """The research document for the model on file and the lab's current database."""
    service = lab.postseason
    status, model = service.status(), service.model()
    if model is None or not status.seasons:
        raise NoPostseasonModel
    built = lab.status()
    parts = [
        "# How Far Can a Team Go?",
        "",
        "The postseason model: how likely each stage of the playoffs is, for a team in the "
        "bracket and for a team of a given strength before the bracket is known - and how "
        "such estimates have come out on seasons the model had not seen. Generated by "
        f"`fol playoffs report --write` from revision {model.revision} of the model (fitted "
        f"{model.fitted_at:%Y-%m-%d}) and build {built.build_id}; do not edit it by hand - "
        "fit the model again, rebuild, and run the command again.",
        "",
        "> Every figure here is an estimate with an interval, scored against what happened "
        "on seasons the model was not fitted to. A chance of 60% means that, of the teams "
        "given about 60%, about 60% got there - the reliability tables say how close that "
        "has held. Nothing here is a guarantee, and nothing is a verdict on a team.",
        "",
        *_notices(status),
        *_what(model),
        *_how(model),
        *_series(model, lab),
        *_bracket(model, lab),
        *_season(model, lab),
        *_limits(),
    ]
    return "\n".join(parts).rstrip("\n") + "\n"


def _notices(status: PostseasonStatus) -> list[str]:
    if status.is_current:
        return []
    return [
        f"> **Out of date.** The model was fitted with top-player quality from value model "
        f"{status.value_model_version}; the database was built with "
        f"{status.applied_value_version}. Run: `{FIT_COMMAND}`, then this command again.",
        "",
    ]


def _what(model: PostseasonModel) -> list[str]:
    spec = model.spec
    return [
        "## What the model is",
        "",
        "Two models share one file; both read two things about a team, each known before "
        "its first playoff game:",
        "",
        "- **Net rating**: the team's regular-season points scored less allowed per 100 "
        "possessions, as the league publishes it.",
        f"- **Top-player quality**: the mean impact, by the value model, of the "
        f"{spec.top_players} players with the highest impact who finished the regular season "
        "with the team - the players a playoff rotation leans on.",
        "",
        "**The series model** is a model of one playoff game - the log-odds that the home "
        "side wins are a home advantage plus a weight per point of the gap in net rating "
        "plus a weight per point of the gap in top-player quality - carried through the "
        f"series format (best of seven in the {spec.default_pattern} pattern, with the "
        "formats of earlier seasons as they were) by enumerating how a series can go. Set "
        "the sixteen playoff teams in their bracket and it gives every team's chance of "
        "every round, exactly, because the two sides of any later matchup are decided "
        "independently.",
        "",
        "**The season model** is for a team before the bracket is known - a roster being "
        "built, a season not yet played. It is the roadmap's hierarchy: the chance of making "
        "the playoffs for any team, of winning a round for a playoff team, of the conference "
        "finals for a team that won a round, and so on to the title, each a logistic in the "
        "same two inputs; the chance of a stage is the steps up to it multiplied together.",
        "",
        "Nothing else is in either model. What else was tried, and what it did on seasons "
        "the model had not seen, is in the tables below; the reasons for what was kept and "
        f"left out are in `{DECISION}`.",
        "",
    ]


def _how(model: PostseasonModel) -> list[str]:
    spec, on = model.spec, model.fitted_on
    tested = model.evaluation
    return [
        "## How it was tested",
        "",
        f"The model is fitted on every season on record ({on.first_season} to "
        f"{on.last_season}: {on.playoff_games:,} playoff games, {on.series} series, "
        f"{on.team_seasons:,} team-seasons). To test it, each season from "
        f"{spec.first_test_season} on was scored with parameters fitted to the seasons "
        "before it alone - the series model on its series, then carried through the "
        "season's actual bracket and scored on where every playoff team got to, and the "
        f"season model on every team-season. That is {tested.series.series} series, "
        f"{tested.bracket.team_postseasons} team-postseasons and {tested.season.team_seasons} "
        "team-seasons the model had not seen when it scored them.",
        "",
        "Two scores are used. **Log loss** is the average surprise at what happened: a "
        "model sure of a thing that did not happen pays dearly, and a coin flip at every "
        "series scores 0.693. **Brier** is the average squared gap between the chance given "
        "and what happened (0 or 1). Lower is better for both. A **calibration slope** near "
        "1 says the chances meant what they said across the range; below 1, the model was "
        "too sure of itself at the extremes. Intervals come from refitting on "
        f"{spec.resamples:,} resamples of whole seasons.",
        "",
    ]


def _series(model: PostseasonModel, lab: Lab) -> list[str]:
    game, tested = model.game, model.evaluation.series
    even = 1 / (1 + 2.718281828459045 ** (-game.home_advantage))
    lines = [
        "## The series model",
        "",
        "| Parameter | Fitted | 95% interval |",
        "| --- | --- | --- |",
        f"| Home advantage (log-odds) | {game.home_advantage:+.3f} | {game.home_low:+.3f} to "
        f"{game.home_high:+.3f} |",
        f"| Per point of net rating | {game.net_rating:.4f} | {game.net_low:.4f} to "
        f"{game.net_high:.4f} |",
        f"| Per point of top-player quality | {game.top_players:.4f} | {game.top_low:.4f} to "
        f"{game.top_high:.4f} |",
        "",
        f"Between two sides equal on both inputs, the home side wins a playoff game "
        f"{even:.1%} of the time. Fitted to one era at a time:",
        "",
        "| Era | Seasons | Games | Home advantage | Per point of net rating | Per point of top-player quality |",
        "| --- | --- | --- | --- | --- | --- |",
        *(
            f"| {era.label} | {era.first_season} to {era.last_season} | {era.games:,} | "
            f"{era.home_advantage:+.3f} | {era.net_rating:.4f} | {era.top_players:.4f} |"
            for era in model.by_era
        ),
        "",
        "### Series, out of sample",
        "",
        f"On {tested.series} series, {tested.first_test_season} to {tested.last_test_season}, "
        f"the home-court side won {tested.home_side_won} and the side the model favoured won "
        f"{tested.favourite_won}.",
        "",
        "| Method | Log loss | Brier |",
        "| --- | --- | --- |",
        f"| The model | {tested.log_loss:.4f} | {tested.brier:.4f} |",
        *(
            f"| {item.label} | {item.log_loss:.4f} | {item.brier:.4f} |"
            for item in tested.baselines
        ),
        "",
        f"Calibration: {_calibration(tested.calibration)}.",
        "",
        *_reliability_table(tested.reliability, "series"),
        "By round:",
        "",
        "| Round | Series | Home side won | Favourite won | Mean chance given the home side | Log loss |",
        "| --- | --- | --- | --- | --- | --- |",
        *(
            f"| {item.round} | {item.series} | {item.home_side_won} | {item.favourite_won} | "
            f"{item.mean_probability:.1%} | {item.log_loss:.4f} |"
            for item in tested.by_round
        ),
        "",
        "By era (each scored out of sample, within the test seasons):",
        "",
        "| Era | Seasons | Series | Log loss | Calibration slope |",
        "| --- | --- | --- | --- | --- |",
        *(
            f"| {item.label} | {item.first_season} to {item.last_season} | {item.series} | "
            f"{item.log_loss:.4f} | {item.calibration.slope:.2f} |"
            for item in tested.by_era
        ),
        "",
        "### What else was tried for series",
        "",
        *_comparisons(tested.comparisons, "the series model"),
    ]
    return lines


def _bracket(model: PostseasonModel, lab: Lab) -> list[str]:
    tested = model.evaluation.bracket
    names = lab.team_labels()["full_name"]
    mean_chance = sum(item.champion_probability for item in tested.favourites) / len(
        tested.favourites
    )
    lowest = min(tested.favourites, key=lambda item: item.champion_probability)
    lines = [
        "## The bracket, out of sample",
        "",
        f"Each test season's sixteen playoff teams were given their chances of every round "
        f"before the first game, from the regular season alone, and scored on where they got "
        f"to: {tested.team_postseasons} team-postseasons.",
        "",
        "| Stage | Teams | Got there | Mean chance | Log loss | Brier | By seed: log loss | Coin flips: log loss | Calibration slope |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        *(_stage_row(item, ("seed_rate", "uniform")) for item in tested.stages),
        "",
        '"By seed" gives every team the share of past teams of its seed that got that far; '
        '"coin flips" gives every series to a coin.',
        "",
        *_reliability_table(tested.reliability, "team-stage cases, all four stages together"),
        f"The title favourite - the team given the best chance before the playoffs - won "
        f"{tested.favourite_won} of {len(tested.favourites)} postseasons. The eventual champion "
        f"had been given {mean_chance:.1%} on average, and as little as "
        f"{lowest.champion_probability:.1%} ({names.get(lowest.champion_team_id, lowest.champion_team_id)}, "
        f"{lowest.season}).",
        "",
        "| Season | Favourite | Chance | Champion | Chance before the playoffs |",
        "| --- | --- | --- | --- | --- |",
        *(
            f"| {item.season} | {names.get(item.favourite_team_id, item.favourite_team_id)} | "
            f"{item.favourite_probability:.1%} | "
            f"{names.get(item.champion_team_id, item.champion_team_id)} | "
            f"{item.champion_probability:.1%} |"
            for item in reversed(tested.favourites)
        ),
        "",
    ]
    return lines


def _season(model: PostseasonModel, lab: Lab) -> list[str]:
    tested = model.evaluation.season
    lines = [
        "## The season model",
        "",
        "Each step is the chance of the next stage for a team that reached this one, as a "
        "logistic in net rating and top-player quality:",
        "",
        "| Step | Teams | Got there | Intercept | Per point of net rating | Per point of top-player quality |",
        "| --- | --- | --- | --- | --- | --- |",
        *(
            f"| {_step_label(step.key, step.from_key)} | {step.teams:,} | {step.reached} | "
            f"{step.intercept:+.3f} | {step.net_rating:+.3f} ({step.net_low:+.3f} to "
            f"{step.net_high:+.3f}) | {step.top_players:+.3f} ({step.top_low:+.3f} to "
            f"{step.top_high:+.3f}) |"
            for step in model.steps
        ),
        "",
        "What that comes to for a team of a given net rating, with the top-player quality "
        "typical of teams at that rating "
        f"({model.typical_top.intercept:+.2f} {model.typical_top.slope:+.3f} per point):",
        "",
        "| Net rating | Top-player quality | "
        + " | ".join(stage(key).short for key in BRACKET_STAGE_KEYS)
        + " |",
        "| --- | --- | " + " | ".join("---" for _ in BRACKET_STAGE_KEYS) + " |",
    ]
    for rating in CURVE_POINTS:
        outlook = lab.postseason.outlook(rating)
        chances = outlook.stages.set_index("key")
        lines.append(
            f"| {rating:+.0f} | {outlook.top_players:+.2f} | "
            + " | ".join(
                f"{chances.at[key, 'probability']:.1%} ({chances.at[key, 'low']:.0%} to "
                f"{chances.at[key, 'high']:.0%})"
                for key in BRACKET_STAGE_KEYS
            )
            + " |"
        )
    lines += [
        "",
        "### Team-seasons, out of sample",
        "",
        f"On {tested.team_seasons} team-seasons:",
        "",
        "| Stage | Teams | Got there | Mean chance | Log loss | Brier | Base rate: log loss | Calibration slope |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
        *(_stage_row(item, ("base_rate",)) for item in tested.stages),
        "",
        '"Base rate" gives every team the share of past teams that got that far.',
        "",
        *_reliability_table(tested.reliability, "team-stage cases, all five stages together"),
        "### What else was tried for seasons",
        "",
        *_comparisons(tested.comparisons, "the season model", per_stage=True),
    ]
    return lines


def _limits() -> list[str]:
    return [
        "## What this does not say",
        "",
        "- The inputs are the regular season's. A star hurt in April, a trade at the deadline "
        "or a rotation that changes for the playoffs is seen only as far as it shows in net "
        "rating and in who finished the season with the team.",
        "- The season model knows nothing of the field: a team's conference, and how strong "
        "the other teams are that season, are not in it. The gap to the conference's "
        "eighth-best rating was tried and helps; it is left out because the model exists to "
        "be read for a roster before a season, when the field is not known.",
        "- The play-in is not modelled. A team that reaches the bracket through it has made "
        "the playoffs like any other.",
        "- Home court in a hypothetical matchup follows the league's main tie-breaks (record, "
        "head to head, seed); the league's full order goes further.",
        "- The series model's parameters have moved across eras - home advantage has "
        "fallen - and the model is fitted to every season at once. The era table shows how "
        "far, and the calibration by era how much it costs.",
        "- A probability is an estimate with an interval. The reliability tables are the "
        "evidence for reading it as one; they are not a promise about any one team.",
        "",
    ]


