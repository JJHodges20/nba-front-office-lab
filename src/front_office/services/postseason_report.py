def _calibration(item: Calibration) -> str:
    return f"slope {item.slope:.2f}, intercept {item.intercept:+.2f}"


def _stage_row(item: StageEvaluation, baseline_keys: tuple[str, ...]) -> str:
    baselines = {baseline.key: baseline for baseline in item.baselines}
    cells = [
        stage(item.key).label,
        f"{item.cases:,}",
        str(item.reached),
        f"{item.mean_probability:.1%}",
        f"{item.log_loss:.4f}",
        f"{item.brier:.4f}",
        *(f"{baselines[key].log_loss:.4f}" for key in baseline_keys),
        f"{item.calibration.slope:.2f}",
    ]
    return "| " + " | ".join(cells) + " |"


def _reliability_table(bins: tuple[ReliabilityBin, ...], what: str) -> list[str]:
    return [
        f"Reliability ({what}): of the cases given a chance in each band, the share that "
        "happened, with its 95% interval.",
        "",
        "| Chance given | Cases | Mean chance | Happened | 95% interval |",
        "| --- | --- | --- | --- | --- |",
        *(
            f"| {item.lower:.0%} to {item.upper:.0%} | {item.cases:,} | {item.predicted:.1%} | "
            f"{item.observed:.1%} | {item.low:.0%} to {item.high:.0%} |"
            for item in bins
        ),
        "",
    ]


def _comparisons(
    items: tuple[Comparison, ...], against: str, *, per_stage: bool = False
) -> list[str]:
    unit = " per stage" if per_stage else ""
    lines = [
        f"Each alternative was tested the same way and scored on the same cases. The change is "
        f"its log loss less {against}'s{unit}: negative is better, and the interval says "
        "whether the difference is clear of zero when whole seasons are resampled.",
        "",
        "| Alternative | Log loss | Brier | Change | 95% interval | Verdict |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for item in items:
        if item.is_clearly_better:
            verdict = "clearly better"
        elif item.is_clearly_worse:
            verdict = "clearly worse"
        else:
            verdict = "not distinguishable"
        lines.append(
            f"| {item.label} | {item.log_loss:.4f} | {item.brier:.4f} | {item.difference:+.4f} | "
            f"{item.low:+.4f} to {item.high:+.4f} | {verdict} |"
        )
    lines.append("")
    return lines


def _step_label(key: str, from_key: str | None) -> str:
    if from_key is None:
        return f"{stage(key).label}, for every team"
    return f"{stage(key).label}, having {_having(from_key)}"


def _having(key: str) -> str:
    label = stage(key).label
    return label[0].lower() + label[1:]


