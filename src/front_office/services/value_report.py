"""The value model written up as a document: ``docs/research/PLAYER_VALUE.md``.

Every figure comes from the fitted model on file or from the database the report is run
against, so the document cannot drift from either: fit the model again, rebuild, run the
report again, and it says what they now say. It only words what
:class:`~front_office.services.value.ValueService` returns.
"""

from __future__ import annotations

import pandas as pd

from front_office.domain.value_model import ValueModel
from front_office.modeling.value import wins_per_net_point
from front_office.services.lab import Lab
from front_office.services.value import LEVELS, MODEL_ROW, TABLE, ModelCard, ValueStatus

TOP = 10
DECISION = "docs/decisions/0010-player-value.md"


class NoValueModel(RuntimeError):
    """There is no fitted model on file, or the database was built without one."""

    def __init__(self) -> None:
        super().__init__(
            "no player values to report: fit the model and rebuild "
            "(fol value fit --write, then fol build)"
        )


def value_report(lab: Lab) -> str:
    """The research document for the fitted model and the lab's current database."""
    service = lab.value
    status, card = service.status(), service.card()
    if card is None or not status.is_available:
        raise NoValueModel
    model = card.model
    built = lab.status()
    parts = [
        "# What a Player Is Worth",
        "",
        "The player value model: what it estimates, how it was tested, and what it found. "
        f"Generated by `fol value report --write` from revision {model.revision} of the "
        f"fitted model (fitted {model.fitted_at:%Y-%m-%d}) and build {built.build_id}; do "
        "not edit it by hand - fit the model, rebuild, and run the command again.",
        "",
        "> Everything here is an estimate. Impact is what a model fitted to thirty seasons "
        "of team results makes of a player's statistics; it is tested on seasons the model "
        "had not seen, and it is wrong by a known amount. It is not a measurement, and no "
        "weight in it is the price of anything.",
        "",
        *_notices(status),
        *_what(model),
        *_test(card),
        *_parts(card),
        *_weights(card),
        *_levels(lab, model),
        *_minutes(model),
        *_leaders(lab, status),
        *_roles(lab, status),
        *_limits(model),
    ]
    return "\n".join(parts)


def _notices(status: ValueStatus) -> list[str]:
    lines = []
    if status.needs_build:
        lines.append(
            f"**Out of date.** The model on file is revision {status.revision}; the values "
            f"in the database were built with {status.applied_revision}. Run `fol build`."
        )
    if status.finished_since:
        lines.append(
            f"**Out of date.** The model was fitted on seasons to {status.fitted_through}; "
            f"{_span(status.finished_since)} finished since. Run `fol value fit --write`."
        )
    return [*lines, ""] if lines else []


def _what(model: ValueModel) -> list[str]:
    on, spec = model.fitted_on, model.spec
    weights = ", ".join(f"{weight:g}" for weight in spec.season_weights)
    return [
        "## What is estimated, and how",
        "",
        "A player's **impact** is the points per 100 possessions a team's net rating gains "
        "with the player on the court, against the league's average minute. It is the sum "
        "of an offensive and a defensive estimate.",
        "",
        "A team's rating in a season is modelled as the sum of its players' estimates, each "
        "counted for the share of the minutes the player actually played, where every "
        "estimate is built **only from seasons before the one predicted**. The weights are "
        "the ones that make that sum come closest to what teams then did. They are chosen "
        "for one thing: describing a player in a way that carries over to next season, on "
        "whatever team.",
        "",
        f"- Fitted on {on.team_seasons:,} team-seasons and {on.player_seasons:,} "
        f"player-seasons, {on.first_season} to {on.last_season}.",
        f"- Earlier seasons are pooled by minutes, newest first, at weights {weights}.",
        f"- A player's own numbers get half the say at {spec.ballast_minutes:g} weighted "
        "minutes; the rest is what is assumed of any player used that many minutes a game.",
        f"- The reasoning behind each choice, and what was tried and left out: `{DECISION}`.",
        "",
    ]


def _test(card: ModelCard) -> list[str]:
    tested, confidence = card.model.validation, f"{card.model.spec.confidence:.0%}"
    lines = [
        "## The test",
        "",
        f"{tested.team_seasons} team-seasons, {tested.first_test_season} to "
        f"{tested.last_test_season}, each predicted with weights fitted only to the seasons "
        "before it. Every method is given next season's actual minutes, so what is compared "
        "is the rating and not a forecast of playing time. Errors are in points of net "
        "rating per 100 possessions.",
        "",
        f"| Method | RMSE | MAE | Value model's RMSE less this ({confidence} interval) |",
        "| --- | ---: | ---: | --- |",
    ]
    for row in card.baselines.itertuples():
        gap = "" if row.key == MODEL_ROW else _gap(row)
        name = f"**{row.label}**" if row.key == MODEL_ROW else row.label
        lines.append(f"| {name} | {row.rmse:.2f} | {row.mae:.2f} | {gap} |")
    seasons = card.by_season
    if not seasons.empty:
        best, worst = seasons.loc[seasons["rmse"].idxmin()], seasons.loc[seasons["rmse"].idxmax()]
        by_end = (
            f"On offense alone the miss is {tested.offense.rmse:.2f}, on defense "
            f"{tested.defense.rmse:.2f}. By season it runs from {best['rmse']:.2f} "
            f"({best['season']}) to {worst['rmse']:.2f} ({worst['season']})."
        )
        lines += ["", by_end]
    lines += [
        "",
        "The intervals come from resampling whole seasons: the teams of one season play "
        "each other and are not independent, so the season is the unit that is drawn. An "
        "interval that stays below zero means the model's advantage is not luck.",
        "",
    ]
    return lines


def _parts(card: ModelCard) -> list[str]:
    confidence = f"{card.model.spec.confidence:.0%}"
    lines = [
        "## What each part adds",
        "",
        "The model fitted again with one part left out, and put through the same test.",
        "",
        f"| Left out | RMSE | RMSE less the full model's ({confidence} interval) | Missed? |",
        "| --- | ---: | --- | --- |",
    ]
    for row in card.ablations.itertuples():
        verdict = "yes" if row.distinguishable else "cannot be told"
        lines.append(f"| {row.label} | {row.rmse:.2f} | {_gap(row)} | {verdict} |")
    unsure = card.ablations.loc[~card.ablations["distinguishable"].astype(bool), "label"]
    if len(unsure):
        lines += [
            "",
            f"{_listed([name.lower() for name in unsure]).capitalize()} cannot be told from "
            "adding nothing on this evidence. They stay in because the box score as a whole "
            "is missed when it goes, but no single weight in them should be leaned on.",
        ]
    return [*lines, ""]


def _weights(card: ModelCard) -> list[str]:
    confidence = f"{card.model.spec.confidence:.0%}"
    lines = [
        "## The weights",
        "",
        "What one more of something per 100 possessions on the court has been worth to a "
        f"team's rating the next season, with {confidence} intervals from resampling "
        "seasons. Not the price of a steal or a rebound: several are wide, and a weight "
        "marked *unclear* cannot be told from zero.",
        "",
        "| Term | Part | Offense | Defense | Both | |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in card.terms.itertuples():
        cells = " | ".join(
            f"{_signed(getattr(row, side))} ({_signed(getattr(row, f'{side}_low'))} to "
            f"{_signed(getattr(row, f'{side}_high'))})"
            for side in ("offense", "defense", "net")
        )
        lines.append(f"| {row.label} | {row.group} | {cells} | {'' if row.known else 'unclear'} |")
    levels = card.terms[card.terms["group"] == LEVELS].set_index("key")["net"]
    lines += [
        "",
        f"The last four rows are levels, not weights of a statistic. A player with no "
        f"earlier season starts at {levels['new_player']:+.2f}. The unproven part of a known "
        f"player is taken to be {levels['prior_level']:+.2f} at the league's average minutes "
        f"per game and {levels['prior_minutes']:+.2f} more for each minute above it. Each "
        f"year of age past {card.model.spec.age_centre:g} moves next season's estimate by "
        f"{levels['age']:+.2f}.",
        "",
    ]
    return lines


def _levels(lab: Lab, model: ValueModel) -> list[str]:
    same, spec = model.validation.same_season, model.spec
    per_point = wins_per_net_point(lab.read("team_seasons"), window=spec.wins_window)
    lines = [
        "## From impact to wins",
        "",
        f"- **Replacement level is {model.replacement_level:+.2f}.** Measured, not assumed: "
        "the minutes-weighted impact of players outside their team's "
        f"{spec.replacement_rank} most-used, over every fitted season.",
    ]
    if not per_point.empty:
        lines.append(
            f"- **A point of net rating has been worth {per_point.min():.2f} to "
            f"{per_point.max():.2f} wins over 82 games**, fitted for each season on that "
            f"season and {spec.wins_window} either side: {per_point.iloc[0]:.2f} in "
            f"{per_point.index[0]}, {per_point.iloc[-1]:.2f} in {per_point.index[-1]}."
        )
    lines += [
        "- **Wins above replacement** are impact over replacement level, times the share "
        "of the team's minutes played, times that season's wins per point.",
        f"- **Impacts are cautious.** A team's net rating is {same.slope:.2f} times the sum "
        f"of its players' impacts in the same season (correlation {same.correlation:.2f}). "
        "Impact is an estimate of ability, not a split of results, and nothing forces the "
        "two to agree.",
        "",
    ]
    return lines


def _minutes(model: ValueModel) -> list[str]:
    minutes = model.availability
    terms = ", ".join(f"{key} {value:+.3f}" for key, value in minutes.coefficients.items())
    return [
        "## Projected minutes",
        "",
        "Next season's share of team minutes, from the last three seasons' shares and age, "
        "fitted on every player seen in those three seasons - including the ones who then "
        "did not play at all.",
        "",
        f"- Tested on {minutes.players:,} player-seasons: RMSE {minutes.rmse:.3f} of a "
        f"team's minutes, against {minutes.baseline_rmse:.3f} for assuming last season's "
        f"share ({minutes.difference:+.3f}, {minutes.low:+.3f} to {minutes.high:+.3f}).",
        f"- Coefficients: {terms}.",
        "- It knows nothing about injuries, trades, contracts or depth charts.",
        "",
    ]


def _leaders(lab: Lab, status: ValueStatus) -> list[str]:
    service = lab.value
    latest = status.seasons[0]
    season = service.season(latest).head(TOP)
    lines = [
        "## Who it rates highest",
        "",
        "Not evidence - the test above is the evidence - but a model that ranked players "
        "nobody would recognise would deserve a second look.",
        "",
        f"**{latest}, by wins above replacement**",
        "",
        "| Player | Team | Impact | Offense | Defense | Share of minutes | WAR |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    lines += [
        f"| {row.player_name} | {row.team} | {row.impact:+.1f} | {row.impact_offense:+.1f} | "
        f"{row.impact_defense:+.1f} | {row.minutes_share:.0%} | {row.wins_added:.1f} |"
        for row in season.itertuples()
    ]
    scores = lab.read(TABLE)
    best = scores[scores["wins_added"].notna()].nlargest(TOP, "wins_added")
    names = lab.read("players", {"player_id": best["player_id"].tolist()})
    names = names.set_index("player_id")["full_name"]
    lines += [
        "",
        f"**The {TOP} most valuable seasons on record**",
        "",
        "| Player | Season | Age | Impact | Share of minutes | WAR |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    lines += [
        f"| {names[row.player_id]} | {row.season} | {row.age} | {row.impact:+.1f} | "
        f"{row.minutes_share:.0%} | {row.wins_added:.1f} |"
        for row in best.itertuples()
    ]
    projected = service.projections().head(TOP)
    if not projected.empty:
        lines += [
            "",
            f"**Projected for {status.upcoming}**",
            "",
            "| Player | Team | Age | Projected impact | Projected share of minutes "
            "| Projected WAR |",
            "| --- | --- | ---: | ---: | ---: | ---: |",
        ]
        lines += [
            f"| {row.player_name} | {_or_dash(row.team)} | {row.age} | "
            f"{row.projected_impact:+.1f} | {row.projected_share:.0%} | "
            f"{row.projected_wins:.1f} |"
            for row in projected.itertuples()
        ]
    return [*lines, ""]


def _roles(lab: Lab, status: ValueStatus) -> list[str]:
    service = lab.value
    latest = status.seasons[0]
    summary = service.role_summary(latest)
    lines = [
        "## The roles",
        "",
        f"Archetypes are rules, not findings (`configs/archetypes.yaml`, version "
        f"{service.archetypes().version}): a player's score for a role is the weakest of "
        "their percentiles on the role's measures, among the players the role is open to, "
        "in that season, and a player fills the role from its cut-off up. Nothing here is "
        "fitted. What can be measured is whether a role is a lasting trait: of the players "
        "who filled it in one season, the share who filled it again in the next, against "
        "the share of everyone scored for it who did.",
        "",
        f"| Role | Open to | Strong on, together | Fills from | Scored in {latest} | "
        "Fill it | Fill it again | Anyone does |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    lines += [
        f"| {row.name} | {row.open_to} | {row.measures} | {row.fills_at:.0f} | {row.scored} | "
        f"{row.filled} | {_share(row.again)} | {_share(row.anyone)} |"
        for row in summary.itertuples()
    ]
    carried = summary[summary["again"].notna() & (summary["anyone"] > 0)]
    if carried.empty:
        lines += ["", "With one season on record, nothing can be said about carrying over."]
    else:
        ratio = carried["again"] / carried["anyone"]
        most, least = carried.loc[ratio.idxmax()], carried.loc[ratio.idxmin()]
        lines += [
            "",
            f"The {most['name'].lower()} carries over most ({most['again']:.0%} against "
            f"{most['anyone']:.0%}) and the {least['name'].lower()} least "
            f"({least['again']:.0%} against {least['anyone']:.0%}).",
        ]
        flat = carried.loc[carried["again"] <= carried["anyone"], "name"].tolist()
        if flat:
            lines[-1] += (
                f" {_listed(flat)} {'is' if len(flat) == 1 else 'are'} filled again no more "
                "often than by anyone: as a lasting trait, nothing."
            )
    return [*lines, ""]


def _limits(model: ValueModel) -> list[str]:
    return [
        "## What it cannot tell you",
        "",
        "- **Defense is the weak side.** A box score records little of it, so the model "
        "leans on the team's own defensive results, shared among the players who were "
        "there. A good defender on a poor defensive team is underrated, and the reverse.",
        "- **The test takes next season's minutes as given.** It shows that the ratings "
        "carry over, not that the lab can foresee who will play.",
        "- **A season is described by its statistics, not by how it was achieved.** Role, "
        "scheme and teammates shape the numbers a player puts up, and the model sees only "
        "the numbers.",
        "- **Playoff performance is not in it.** Counting playoff minutes did not help "
        "predict the next season, so they are left out; whether they matter in the playoffs "
        "is a different question.",
        f"- **It must be fitted again when a season ends.** This revision knows seasons to "
        f"{model.fitted_on.last_season}.",
        "",
    ]


def _signed(value: float) -> str:
    """A number to two decimals with its sign; nothing so small it rounds away is negative."""
    return f"{round(value, 2) + 0.0:+.2f}"


def _gap(row) -> str:  # type: ignore[no-untyped-def]
    return f"{_signed(row.difference)} ({_signed(row.low)} to {_signed(row.high)})"


def _span(seasons: tuple[str, ...]) -> str:
    return seasons[0] if len(seasons) == 1 else f"{seasons[0]} to {seasons[-1]}"


def _listed(names: list[str]) -> str:
    if len(names) <= 1:
        return "".join(names)
    return ", ".join(names[:-1]) + " and " + names[-1]


def _share(value: float) -> str:
    return "-" if pd.isna(value) else f"{value:.0%}"


def _or_dash(value: object) -> str:
    return "-" if pd.isna(value) else str(value)
