"""The search-quality evaluation's counting (A7), on invented results: the live run is
``scripts/evaluate_search.py``."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

from front_office.assistant.search_quality import (
    Result,
    SearchCase,
    load_search_cases,
    report,
    score_case,
    score_record,
)
from front_office.config import load_assistant_settings

ROOT = Path(__file__).resolve().parents[3]
NOW = datetime(2026, 10, 10, 20, 0)
CASE = SearchCase(
    id="Q01",
    query="Boston Celtics injury news",
    kind="news",
    names=("Celtics",),
    days=14,
    team="BOS",
)


def test_the_frozen_queries_are_well_formed() -> None:
    cases = load_search_cases(ROOT / "tests" / "assistant" / "fixtures" / "search_cases.yaml")
    ids = [case.id for case in cases.cases]
    assert len(ids) == len(set(ids)) >= 12
    assert all(case.days is not None for case in cases.cases if case.kind == "news")
    news = load_assistant_settings(ROOT / "configs").news
    assert all(news.team_feed(case.team) for case in cases.cases if case.team), "a feed each"


def test_a_run_is_counted_result_by_result() -> None:
    found = [
        Result("Celtics injury update", "https://a.example/2026/10/08/x", "Tatum", datetime(2026, 10, 8)),
        Result("Celtics injury update", "https://a.example/2026/10/08/x?utm_source=s", "", datetime(2026, 10, 8), duplicate=True),
        Result("Old Celtics story", "https://b.example/2026/01/y", "", datetime(2026, 1, 1)),
        Result("League notes", "https://c.example/notes", "No team named", None),
        Result("Celtics salaries", "https://www.spotrac.com/nba/boston-celtics/", "", None, refused=True),
    ]  # fmt: skip
    feed = [
        Result("Celtics Notes: Tatum", "https://h.example/1", "", datetime(2026, 10, 9)),
        Result(
            "Atlantic Notes", "https://h.example/2", "Celtics and Knicks", datetime(2026, 10, 1)
        ),
        Result("Celtics Camp", "https://h.example/3", "", datetime(2026, 9, 1)),
    ]
    score = score_case(CASE, found, feed, now=NOW)
    assert (score.results, score.left_out, score.duplicates) == (5, 1, 1)
    assert (score.on_topic, score.dated, score.fresh) == (2, 2, 1), "of three kept"
    assert (score.feed_items, score.feed_on_topic) == (2, 2), "the feed's items of the 14 days"


def test_the_report_gives_each_query_and_the_whole() -> None:
    scores = [
        score_case(
            CASE,
            [Result("Celtics", "https://a.example/2026/10/09/x", "", datetime(2026, 10, 9))],
            [],
            now=NOW,
        ),  # fmt: skip
        score_case(
            SearchCase(id="B01", query="Celtics 2008", kind="background", names=("Celtics",)),
            [],
            None,
            now=NOW,
            error="Ollama's web search allowance is used up for now (429)",
        ),
    ]
    text = report(
        {
            "ran_at": "2026-10-10 20:00",
            "max_results": 10,
            "scores": [score_record(s) for s in scores],
        }
    )
    assert text.startswith("<!-- Generated by `scripts/evaluate_search.py --write`.")
    assert "| Q01 | Boston Celtics injury news | news | 1 | 0 | 0 | 1 | 1 | 1 | 0 (0) |" in text
    assert "| B01 | Celtics 2008 | background | not run: Ollama's web search allowance" in text
    assert "- Queries run: 1 of 2." in text
    assert "Counts, not thresholds" in text
